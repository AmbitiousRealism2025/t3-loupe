// Regenerates plugin/lib/Icons.js from a local lucide-react install.
// Usage: node tools/extract-icons.mjs <path-to-lucide-react>
// Parses __iconNode literals as text (no code from the package is executed)
// and converts every element to an SVG path string for QtQuick.Shapes PathSvg.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ICONS = [
  // T3 timeline activity icons (MessagesTimeline.tsx WorkEntryIcon)
  "terminal", "square-pen", "eye", "search", "globe", "brain", "bot", "hammer", "wrench",
  "message-circle", "circle-alert", "check", "zap", "app-window", "monitor", "list-todo", "sparkles", "layers",
  // states and chrome
  "git-pull-request", "git-merge", "git-branch", "circle-check", "circle-x", "circle-dashed", "hourglass",
  "clock", "pause", "circle-pause", "loader-circle", "x", "refresh-cw", "external-link", "copy", "pin", "moon",
  "server", "laptop", "gauge", "coins", "folder", "chevron-right", "chevron-down", "bell", "plug-zap",
  "shield-alert", "message-circle-question", "notebook-pen", "users", "activity", "cpu", "key-round", "circle-dot",
  "a-arrow-up", "a-arrow-down",
];

const lucide = process.argv[2];
if (!lucide) throw new Error("usage: extract-icons.mjs <lucide-react dir>");
const version = JSON.parse(readFileSync(join(lucide, "package.json"), "utf8")).version;

const num = (v) => Number(v ?? 0);
function rect(a) {
  const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height);
  const rx = Math.min(num(a.rx ?? a.ry), w / 2), ry = Math.min(num(a.ry ?? a.rx), h / 2);
  if (!rx) return `M${x} ${y}h${w}v${h}h${-w}Z`;
  return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`;
}
function ellipse(cx, cy, rx, ry) {
  return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`;
}
function toPath(tag, a) {
  switch (tag) {
    // A leading relative moveto is absolute only at the very start of a path;
    // make it explicit so subpaths can be concatenated into one PathSvg.
    // Rewrite it as an absolute M plus a relative l, so implicit coordinate pairs stay relative.
    case "path": return a.d.replace(/^m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)\s*,?\s*(?=[-\d.])/, "M$1 $2 l").replace(/^m/, "M");
    case "rect": return rect(a);
    case "circle": return ellipse(num(a.cx), num(a.cy), num(a.r), num(a.r));
    case "ellipse": return ellipse(num(a.cx), num(a.cy), num(a.rx), num(a.ry));
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon": {
      const pts = String(a.points).trim().split(/[\s,]+/).map(Number);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === "polygon" ? d + "Z" : d;
    }
  }
  throw new Error(`unsupported element ${tag}`);
}

const out = {};
for (const name of ICONS) {
  let src = readFileSync(join(lucide, "dist/esm/icons", `${name}.mjs`), "utf8");
  // Renamed icons are re-export stubs: follow them.
  const alias = /export \{ default \} from '\.\/([\w-]+)\.mjs'/.exec(src);
  if (alias) src = readFileSync(join(lucide, "dist/esm/icons", `${alias[1]}.mjs`), "utf8");
  const node = /const __iconNode = \[([\s\S]*?)\];\s*\nconst /.exec(src)?.[1];
  if (!node) throw new Error(`no icon node in ${name}`);
  const parts = [];
  for (const m of node.matchAll(/\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]/g)) {
    const attrs = Object.fromEntries([...m[2].matchAll(/(\w+):\s*"([^"]*)"/g)].map((a) => [a[1], a[2]]));
    parts.push(toPath(m[1], attrs));
  }
  if (!parts.length) throw new Error(`no elements parsed for ${name}`);
  out[name] = parts;
}

writeFileSync(new URL("../plugin/lib/Icons.js", import.meta.url), `.pragma library

// Generated by tools/extract-icons.mjs from lucide-react ${version} — do not edit.
// Lucide icons: ISC License, Copyright (c) Lucide Icons and Contributors (see THIRD_PARTY.md).
// Each icon is a list of SVG path strings on a 24×24 grid, drawn as 2px round strokes.

var paths = ${JSON.stringify(out, null, 1)}

function get(name) { return paths[name] || paths["circle-dot"] }

// All subpaths joined: one PathSvg can draw the whole icon.
function svg(name) { return get(name).join(" ") }
`);
console.log(`wrote ${ICONS.length} icons from lucide-react ${version}`);
